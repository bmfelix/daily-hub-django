# Channels delivers live updates (the Radio card) over WebSockets. Redis lets the
# listener worker and the web server share messages; without it (tests, local
# runs) messages stay inside one process.
if os.environ.get("REDIS_URL"):
    CHANNEL_LAYERS = {
        "default": {
            "BACKEND": "channels_redis.core.RedisChannelLayer",
            # redis-py 8 times out reads after 5 seconds, the same length as the
            # layer's blocking read, so allow longer to avoid spurious timeouts.
            "CONFIG": {"hosts": [{"address": os.environ["REDIS_URL"], "socket_timeout": 15}]},
        }
    }
else:
    CHANNEL_LAYERS = {"default": {"BACKEND": "channels.layers.InMemoryChannelLayer"}}


